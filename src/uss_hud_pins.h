/* HellForge relocates these two RIP-relative references together. Keep every
 * opcode and surrounding byte pinned; only the reviewed rel32 fields may move.
 * Two passes reject a table switch while its address is being resolved. */
static inline int uss_hud_projectile_table(Reader* reader,uintptr_t base,uintptr_t* table)
{
    const unsigned indexes[2]={1,4},offsets[2]={3,11},ends[2]={7,15};
    unsigned pass,i,j;uintptr_t target=0;unsigned char bytes[36],first[2][36];
    for(pass=0;pass<2;++pass)for(i=0;i<2;++i){
        const UssHudPin* pin=&uss_hud_pins[indexes[i]];int32_t displacement;int64_t resolved;
        if(!get(reader,base+pin->rva,bytes,pin->size))return 0;
        for(j=0;j<pin->size;++j)if((j<offsets[i] || j>=offsets[i]+4) && bytes[j]!=pin->bytes[j])return 0;
        if(pass && memcmp(first[i],bytes,pin->size))return 0;
        if(!pass)memcpy(first[i],bytes,pin->size);
        memcpy(&displacement,bytes+offsets[i],4);
        resolved=(int64_t)(base+pin->rva+ends[i])+displacement;
        if(resolved<=0 || (uintptr_t)resolved<base || (uintptr_t)resolved-base>0x80000000u ||
            ((uintptr_t)resolved&7) || !address_ok((uintptr_t)resolved,8))return 0;
        if(target && target!=(uintptr_t)resolved)return 0;
        target=(uintptr_t)resolved;
    }
    {unsigned char first_slot[8];if(!get(reader,target,first_slot,8))return 0;}
    *table=target;return 1;
}
