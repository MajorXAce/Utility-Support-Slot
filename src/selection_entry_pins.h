/* Exact supported-build entry bytes; validates addresses, never calls them. */
#ifndef USS_SELECTION_ENTRY_PINS_H
#define USS_SELECTION_ENTRY_PINS_H
#include "../ResearchSource/inventory_reader.h"
typedef struct UssSelectionAddresses { uintptr_t state,weapon; } UssSelectionAddresses;
static int uss_selection_entry_pins(Reader* reader,uintptr_t base,size_t size,
                                     UssSelectionAddresses* output)
{
    unsigned char bytes[64];
    static const unsigned char state_pin[64]={0x4c,0x8b,0xdc,0x55,0x57,0x48,0x8b,0xec,0x48,0x83,0xec,0x78,0x48,0x8b,0x05,0x6d,0x81,0xba,0x01,0x48,0x33,0xc4,0x48,0x89,0x45,0xe0,0x8b,0x01,0x48,0x8b,0xf9,0x49,0x89,0x5b,0x10,0x33,0xdb,0x3b,0x05,0x65,0xfd,0x9e,0x02,0x49,0x89,0x73,0x18,0x8b,0xf2,0x4d,0x89,0x63,0x20,0x4d,0x89,0x6b,0xe8,0x4d,0x89,0x73,0xe0,0x4c,0x8b,0x35};
    static const unsigned char weapon_pin[64]={0x48,0x8b,0xc4,0x44,0x89,0x40,0x18,0x53,0x55,0x41,0x55,0x48,0x81,0xec,0x80,0x00,0x00,0x00,0x3b,0x15,0xb8,0x91,0xad,0x02,0x41,0x8b,0xe8,0x8b,0xda,0x4c,0x8b,0xe9,0x0f,0x84,0x94,0x06,0x00,0x00,0x44,0x8b,0x49,0x30,0x44,0x8b,0x51,0x38,0x48,0x89,0x70,0x08,0x4c,0x89,0x70,0xd0,0x45,0x33,0xf6,0x44,0x0f,0xaf,0xd3,0x41,0x8d,0x71};
    memset(output,0,sizeof(*output));
    if (!base || size<0xA93ED0 || size>0x20000000) return 0;
    if (!get(reader,base+0xA93E90,bytes,64) || memcmp(bytes,state_pin,64) ||
        !get(reader,base+0x9AAA50,bytes,64) || memcmp(bytes,weapon_pin,64)) return 0;
    output->state=base+0xA93E90; output->weapon=base+0x9AAA50;
    return 1;
}
#endif
